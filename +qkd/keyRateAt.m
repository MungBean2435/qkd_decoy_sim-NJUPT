function [R, d] = keyRateAt(p, L, spec)
%KEYRATEAT 某个距离上，一个脉冲平均能剩下多少比特密钥（对应指导书 (3.30)）
%
%   [R, d] = qkd.keyRateAt(p, L, spec)
%
% ------------------------------------------------------------------------
%  大白话：这一步算的是「收入 - 支出」。
%
%  收入 = 单光子那部分脉冲 × 每比特里去掉 Eve 可能知道的部分
%  支出 = 纠错时必须公开的比特数（公开的比特不能当密钥用）
%
%  写成公式（(3.30)）：
%      R ≥ P_u·P^A_{Z|u}·P^B_Z · { P1^u·Y~1^{Z,L}·[1 - H2(e~1^{X,U})] - Q_u·f·H2(E_u) }
%          └───── 资格系数 ─────┘   └──────── 收入 ────────┘   └── 支出 ──┘
%
%  逐项解释：
%     P_u·P^A_{Z|u}·P^B_Z
%         「有资格参与成码」的脉冲比例：必须是信号态、Alice 选了 Z 基、
%         而且 Bob 也选了 Z 基。三条同时满足才行，所以是连乘。
%         （其余的脉冲没白费，它们去 X 基当「体检样本」了。）
%
%     P1^u          信号态里恰好 1 个光子的概率（泊松）。只有这种才真正安全。
%     Y~1^{Z,L}     单光子响应率的下界（estimate.m 算的）。
%     [1 - H2(e~1^{X,U})]
%                   「隐私放大」要扣掉的部分：Eve 可能掌握了 e1 那么多信息，
%                   所以这部分的比特不能全留。
%     Q_u·f·H2(E_u)  纠错要公开的比特量：Q_u 是有响应的比例，E_u 是误码率，
%                   H2 把它换算成比特，f=1.16 是实际纠错的额外开销。
%
%  H2(x) 叫二进制熵，作用是把「一个比例」换算成「需要多少比特」。
%  直观理解：x=0 或 1 时完全确定，H2=0（不花比特）；x=0.5 时最难猜，H2=1
%  （一个比特全得花掉）。误码越多、越接近 50%，纠错就越贵。
% ------------------------------------------------------------------------
%
%  L 可以是单个数字或一串数字；p 里的 u/v/Pu/Pv 可以被优化器改掉后重复调用。
%  换句话说，本函数是「纯函数」：同样的输入永远给同样的输出，
%  所以优化器可以放心地拿它当目标函数反复试参数。
% ------------------------------------------------------------------------

if ~isfield(spec, 'eps') || isempty(spec.eps)
    spec.eps = 1e-7;      % 没给就说错概率取默认值（和 fluct.m 保持一致）
end

% 第一步：请 estimate.m 把两个单光子参数估出来（这是全工程最重的计算）
[Y1Lz, e1Ux, d] = qkd.estimate(p, L, spec);

% 第二步：把画图/报告要用的量塞进 d（不影响结果，只是顺便带出去）
d.P1u  = exp(-p.u) .* p.u;   % 泊松：恰好 1 个光子的概率 = e^{-u}·u
d.e1Ux = e1Ux;
d.Y1Lz = Y1Lz;

% 二进制熵 H2(x) = -x·log2(x) - (1-x)·log2(1-x)
% 里面套 max(…, realmin) 是防 log2(0) 变成 -Inf 的经典写法。
H2 = @(x) -(x .* log2(max(x, realmin)) + (1 - x) .* log2(max(1 - x, realmin)));

% 第三步：(3.30) 本体 —— 收入减支出，再乘上资格系数。
% 注意 MATLAB 里这行是「向量化」的：L 是数组时，一次就能算出所有距离点的 R。
R = p.Pu .* p.Pza_u .* p.Pzb .* ...
    (d.P1u .* Y1Lz .* (1 - H2(e1Ux)) - d.Qu .* p.f .* H2(d.Eu));

% 第四步：把不讲理的结果拦住。
% R 算出负数/NaN 的含义是「这段距离根本没有安全密钥」，通信应该停在这里，
% 而不是把它当成「负的密钥率」画到图上去。
R(~isfinite(R)) = 0;    % 挡住 NaN、Inf
R(R < 0) = 0;           % 负数一律按 0 处理

end
