function g = gain(p, L)
%GAIN 算一算：光飞了 L 公里之后，还剩多少、Bob 能收到多少、收错了多少
%
%   g = qkd.gain(p, L)
%
% ------------------------------------------------------------------------
%  大白话版：一个脉冲发出去，最后只会是三种结局之一
%
%     ① Bob 一点反应都没有            → 没收到，或者收到了但没抓住
%     ② Bob 有反应，而且判断对了
%     ③ Bob 有反应，但判断错了（误码）
%
%  Q（增益）=「有反应」的概率 = ②+③
%  E（误码率）= 有反应的里面，错的那部分占多少 = ③/(②+③)
%  T（误码计数）= 错的概率 = ③ = Q*E
%
%  所以记住一句话：Q 管「响不响」，E 管「响得对不对」，T 是两者的乘积。
% ------------------------------------------------------------------------
%
%  这一层只管「概率」，不管「有多少个脉冲」。乘上脉冲数变成计数，是上一层
%  estimate.m 干的事。这样分开写，改距离只影响这里，改脉冲数只影响那里。
%
%  L 可以是单个数字，也可以是一串数字（比如 0:1:300）。
%  传一串进去，下面每行都会一次算出 301 个结果 —— 这叫「向量化」，
%  是 MATLAB 的基本功，也是优化器能一次评估几百个候选参数的原因。
%
%  四个式子（对应指导书 (3.8) 与 (3.27)）：
%       透过率   eta  = etad * 10^(-alpha*L/10)          ← 把 dB 换成「还剩几成」
%       增益     Q_l  = Y0 + 1 - exp(-eta*l)             ← 至少一个光子被收到
%       误码率   E_l  = (e0*Y0 + e_d*(1-exp(-eta*l))) / Q_l
%       误码计数 T_l  = E_l * Q_l
%
%  符号：l 是光强（u 或 v），eta 是总透过率，Y0 是探测器自己瞎响的概率。
% ------------------------------------------------------------------------

g = struct();

% 透过率：光飞 L 公里后还剩几成。
% 物理：每公里掉 alpha 分贝，L 公里掉 alpha*L 分贝，换成倍数就是 10^(-alpha*L/10)。
% 举个具体数字：L=100、alpha=0.2 → 10^(-2) = 0.01，也就是只剩 1%；
% 再乘上探测器效率 etad=0.5 → eta≈0.005，也就是说一万个光子到一个。
g.eta = p.etad .* 10 .^ (-p.alpha .* L ./ 10);

% 一个脉冲里「至少有一个光子被收到」的概率。
% 泊松分布里「一个都没收到」的概率是 exp(-eta*l)，所以「至少一个」就是 1 减去它。
% 信号态、诱骗态各算一遍，因为光强不同、这个概率也不同。
g.eta_u = 1 - exp(-g.eta .* p.u);
g.eta_v = 1 - exp(-g.eta .* p.v);

% 总增益 Q = 真实光子被收到的概率 + 探测器自己瞎响的概率。
% 所以 Q 一定大于 Y0：你发了光，只会让「有反应」更容易，不会更难。
g.Qu = p.Y0 + g.eta_u;
g.Qv = p.Y0 + g.eta_v;

% 误码率 E = 错误事件占所有响应的比例。
% 分子是两类错误的概率相加：
%   e0*Y0                 ← 没收到光子、纯靠瞎猜而猜错
%   e_d*(1-e^{-eta*l})    ← 真光子收到了，但器件/对准不完美导致判错
% 分母是总响应概率 Q，这样除完就是「响应里错的比例」。
g.Eu = (p.e0 .* p.Y0 + p.ed .* g.eta_u) ./ g.Qu;
g.Ev = (p.e0 .* p.Y0 + p.ed .* g.eta_v) ./ g.Qv;

% 误码计数 T = E*Q，也就是「这个脉冲既是响应的、又是错的」的概率。
% 为什么要单独存一份？因为后面两种统计界（霍夫丁、切尔诺夫）是拿「计数」
% 去定界的，直接传 T 进去最省事，也不用反复乘除（见 fluct.m 的 D.T）。
g.Tu = g.Eu .* g.Qu;
g.Tv = g.Ev .* g.Qv;

end
