function [Y1Lz, e1Ux, d] = estimate(p, L, spec)
%ESTIMATE 诱骗态估计：从「能测到的总数」反推「测不到的单光子」
%
%   [Y1Lz, e1Ux, d] = qkd.estimate(p, L, spec)
%
% ------------------------------------------------------------------------
%  这是整个工程最核心、也最难的一段。读之前先想清楚两个事实：
%
%  事实一：真正安全的只有「单光子脉冲」。
%     一个脉冲里如果塞了两个以上光子，Eve 可以拿走一个、留一个给 Bob，
%     Bob 照样收到、照样不出错，Eve 却已经知道了这个比特。这种攻击叫
%     PNS（光子数分裂）。所以算密钥时，只能把单光子那部分的贡献算进去。
%
%  事实二：单光子是「看不见」的。
%     弱相干光源发出来的脉冲，光子数服从泊松分布：u=0.5 时大约 30% 是单光子、
%     7.6% 是双光子以上、60% 干脆是空的。可是 Bob 收到响应之后，他只知道自己
%     「收到了」，根本不知道刚才那个脉冲里原本有几个光子。这些数据全混在一起。
%
%  诱骗态就是用来解开这个死结的：Alice 随机切换强弱两种光强，Eve 分不清哪个
%  脉冲是哪种强度，只能一视同仁地偷。于是两种强度的数据里，「被偷的比例」相同，
%  两个方程一联立，就能把「单光子贡献了多少」反解出来。
%
%  本函数要算出两个量（都取「对自己不利」的那一侧，宁少勿多）：
%     Y1Lz = Z 基单光子响应率的 **下界**（往小了估，对应 (3.28)）
%     e1Ux = X 基单光子误码率的 **上界**（往大了估，对应 (3.29)）
% ------------------------------------------------------------------------
%
%  输入
%     p    : qkd.params() 给的参数（优化时 u、v、Pu、Pv 会被调用方改掉）
%     L    : 距离（km），可以是数组
%     spec : 需要 .N（脉冲数）、.method（哪种界）、.eps（说错的概率）
%
%  输出
%     d    : 一堆中间量（Qu、Qv、Eu、Ev、P1u……），画图和排查问题时很有用
%
% ------------------------------------------------------------------------
%  两个公式怎么读（对应指导书 (3.28)(3.29)）
%
%  (3.28)  Y~1^{W,L} = [P2^u·Qv^L - P2^v·Qu^U + (P2^v·P0^u - P2^u·P0^v)·Y0^U]
%                      / (P1^v·P2^u - P1^u·P2^v)
%
%      P1^u、P2^u = 光强 u 的脉冲里「恰好 1 个光子」「恰好 2 个光子」的概率（泊松）。
%      分子里的每一项都在往「让小 Y1 更小」的方向取：
%          Qv^L 用下界（诱骗态收到的少一点，单光子估计就更保守）
%          Qu^U 用上界（信号态收到的多一点，扣掉的更多）
%          Y0^U 用上界（暗计数多说一点，能归功给单光子的就更少）
%      分母 = P1^v·P2^u - P1^u·P2^v，只要 u > v 就恒为正 —— 这就是为什么
%      诱骗态必须比信号态弱。如果 v > u，分母变号，整个估计就废了。
%
%  (3.29)  e~1^{X,U} = (Tv^U - P0^v·e0·Y0^L) / (P1^v·Y~1^{X,L})
%
%      思路：X 基收到的错误总数，先扣掉「真空态瞎猜贡献的那部分错误」，
%      剩下的错误全是单光子造成的，再除以单光子的数量，就得到单光子误码率。
%      分子用 Tv^U（错误多说一点），分母用 Y1 的下界（分母小一点 → 结果大一点），
%      两个方向都是「往坏处算」。
% ------------------------------------------------------------------------

% 先把「这一种统计界」请出来（高斯/霍夫丁/切尔诺夫，差别只在留多少余量）
D  = qkd.fluct(spec.method, spec.eps);
% 再拿到这条链路的增益、误码率等概率（不含量子数，只管物理）
g  = qkd.gain(p, L);
N  = spec.N;
% 泊松分布：光强 l 的脉冲里恰好有 n 个光子的概率。这就是「弱相干光源」的定义式。
np = @(n, l) exp(-l) .* l.^n ./ factorial(n);   % MATLAB：factorial 就是阶乘

% ---- 第一步：算清楚「每种强度、每个基，各发了多少个脉冲」----
% BB84 里 Alice 要选强度，还要选基（Z 基成码、X 基查错）。
% 所以「Z 基里的信号态脉冲数」= 总脉冲数 × 选信号态的概率 × 选 Z 基的概率。
wZ_u = p.Pza_u;       % 信号态选 Z 基的概率
wZ_v = p.Pza_v;       % 诱骗态选 Z 基的概率
wX_u = 1 - p.Pza_u;   % 剩下的就是 X 基（本工程里两基概率互补）
wX_v = 1 - p.Pza_v;

NuZ = p.Pu * wZ_u * N;   % Z 基里信号态的脉冲数
NvZ = p.Pv * wZ_v * N;   % Z 基里诱骗态的脉冲数
NuX = p.Pu * wX_u * N;   % X 基里信号态的脉冲数
NvX = p.Pv * wX_v * N;   % X 基里诱骗态的脉冲数
N0  = p.P0 * N;          % 真空态脉冲数（真空不选基，所以不分 Z/X）

% ---- 第二步：给真空态响应率定一个区间 ----
% 真空态脉冲里一个光子都没有，Bob 却报「收到了」，那只能是暗计数。
% 所以它是最干净的暗计数测量。我们用它的上下界去校准后面所有估计。
[Y0_lo, Y0_hi] = D.Y0(p.Y0, N0);

% ---- 第三步：Z 基（成码用）—— 给增益定区间 ----
% nWz 是这个基里收到的「总事件数」，霍夫丁界要用它（指导书 (3.33)）。
nWz = NuZ .* g.Qu + NvZ .* g.Qv;
% 注意：估单光子响应率时，诱骗态取下界、信号态取上界（见上面公式解释）
[QuZ_lo, QuZ_hi] = D.Q(g.Qu, NuZ, nWz);
[QvZ_lo, QvZ_hi] = D.Q(g.Qv, NvZ, nWz);

% ---- 第四步：X 基（查错用）—— 同样定区间 ----
nWx = NuX .* g.Qu + NvX .* g.Qv;
[QuX_lo, QuX_hi] = D.Q(g.Qu, NuX, nWx);
[QvX_lo, QvX_hi] = D.Q(g.Qv, NvX, nWx);
% 误码计数只需要上界（错误往多了算才安全），下界用 ~ 丢掉不用
[~, TvX_hi]      = D.T(g.Tv, NvX, nWx);

% ---- 第五步：算泊松项 ----
% Pn_l = 光强 l 的脉冲里恰好 n 个光子的概率。单光子是 P1、双光子是 P2、真空是 P0。
P1u = np(1, p.u);  P2u = np(2, p.u);  P0u = np(0, p.u);
P1v = np(1, p.v);  P2v = np(2, p.v);  P0v = np(0, p.v);
den = P1v .* P2u - P1u .* P2v;   % (3.28) 的分母；只要 u > v 就恒为正

% ---- 第六步：套 (3.28)，得到 Z 基单光子响应率的下界 ----
% 这一行是整个工程最重要的一行。逐项对应公式即可，不用背。
Y1Lz = (P2u .* QvZ_lo - P2v .* QuZ_hi + (P2v .* P0u - P2u .* P0v) .* Y0_hi) ./ den;
Y1Lz = max(Y1Lz, 0);      % 物理上不可能是负的；估成负数就说明这一段没密钥

% ---- 第七步：X 基再算一次（同一个公式，只是基不同）----
% X 基的单光子响应率主要用来当 (3.29) 的分母。
Y1Lx = (P2u .* QvX_lo - P2v .* QuX_hi + (P2v .* P0u - P2u .* P0v) .* Y0_hi) ./ den;
Y1Lx = max(Y1Lx, 0);

% ---- 第八步：套 (3.29)，得到单光子误码率的上界 ----
% 分子：X 基收到的错误总数，扣掉真空态瞎猜贡献的那部分
% 分母：单光子数量（取下界）→ 分母更小 → 结果更大 → 更保守
e1Ux = (TvX_hi - P0v .* p.e0 .* Y0_lo) ./ (P1v .* max(Y1Lx, realmin));
e1Ux = min(max(e1Ux, 0), 0.5);   % 误码率只能在 [0, 0.5]：超过 0.5 说明数据全反了

% 如果连单光子响应率都估不出来（<=0），那就没有资格谈误码率，
% 只能按最坏情况处理：e1 = 0.5，即「单光子脉冲的误码等同于纯瞎猜」。
% 这样算出来的密钥率会直接被压到 0 —— 保守，但安全。
e1Ux(Y1Lx <= 0) = 0.5;

% ---- 第九步：把中间量打包返回（不参与安全判定，只为了方便画图和排查）----
d.Qu = g.Qu;   d.Qv = g.Qv;          % 增益
d.Eu = g.Eu;   d.Ev = g.Ev;          % 误码率
d.Y0_lo = Y0_lo;   d.Y0_hi = Y0_hi;  % 暗计数的上下界
d.Y1Lx = Y1Lx;                       % X 基单光子响应率下界
d.P1u = P1u;   d.P1v = P1v;   d.den = den;   % 三个泊松项和分母，答辩常被问
d.nuZ = NuZ;   d.nvZ = NvZ;          % Z 基各强度的脉冲数

end
