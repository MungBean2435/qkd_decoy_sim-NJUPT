function p = params()
%PARAMS 题目给的固定参数表（2026 软件设计题目 · 表 1：三强度诱骗态 BB84）
%
%   p = qkd.params()
%
% ------------------------------------------------------------------------
%  一句话：这个文件就是整个工程的「参数总表」。
%
%  所有物理常数只写在这里。想换场景（换光纤、换探测器、换光强），
%  只改这个文件，别的地方一行都不用动。
% ------------------------------------------------------------------------
%
%  返回值 p 是一个「结构体」（struct），你可以把它想成一个贴了标签的抽屉，
%  每个字段就是一个小格子，比如 p.u 就是「信号态光强」那一格。
%  字段名和题目表 1 一一对应，答辩时可以对着表逐项核对：
%      u  v  Pu  Pv  Pza_u  Pza_v  Pzb  f  alpha  etad  d  etaA  dA  ed  e0
%  另外还有两个「顺手算出来」的量：Y0（真空态响应率）和 P0（真空态概率），
%  它们由上面的字段推出来，后面 gain.m、estimate.m 会反复用到，就先算好放这儿。
%
% ------------------------------------------------------------------------
%  看代码之前，先接受下面三句话，后面就都好懂了
%
%  1) u、v 不是「几个光子」，而是「平均几个光子」。
%     激光衰减之后，每个脉冲里到底有几个光子是随机的：有的一个没有，
%     有的一个，偶尔还有两个、三个。平均下来等于 u。
%     「平均是 0.5 个」的意思是有一半左右的脉冲是空的、快一半是单光子、
%     还有百分之几是两光子以上——就是这几%给了小偷可乘之机（见诱骗态）。
%
%  2) Pu、Pv、P0 是「三种脉冲各占多少」，加起来必须正好是 1。
%     本方案只有三种：信号态（强）、诱骗态（弱）、真空态（干脆不发光）。
%     所以只要定了 Pu、Pv，真空态 P0 就自动定了，见文件最后一行。
%
%  3) alpha = 0.2 的意思是「每公里少 0.2 分贝」。
%     换成大白话：光在光纤里是越走越少的，飞 100 km 只剩下百分之一。
%     具体怎么换算是 gain.m 第一行代码的事。
% ------------------------------------------------------------------------

p = struct();   % 先建一个空抽屉，再往里一格一格放东西

% ---- 光强与选择概率 ----
% Alice 每发一个脉冲，先从三种强度里挑一种（这就是「三强度」），再挑一个基。
%   u = 信号态（强）：主要用来生成密钥。光子多→收到的多→误差小，
%                     但多光子的比例也高，安全性得靠诱骗态兜着。
%   v = 诱骗态（弱）：专门用来给 Eve 「下套」。配合信号态的数据，
%                     就能反推出「单光子」到底贡献了多少，见 estimate.m。
%   真空态：不发光子。用来直接量一量 Bob 的探测器有多爱「自己瞎响」。
p.u     = 0.5;      % 信号态光强 u（平均光子数；只是个平均数，不是确定值）
p.v     = 0.1;      % 诱骗态光强 v（必须比 u 小，否则公式分母会变号，见 estimate.m）
p.Pu    = 0.6;      % 信号态选择概率：60% 的脉冲用强的
p.Pv    = 0.3;      % 诱骗态选择概率：30% 的脉冲用弱的

% BB84 有两个「基」，可以理解成两套暗号：Z 基用来生成密钥，X 基用来查误码。
% 下面三行是「在某个强度下，选 Z 基的概率」。
p.Pza_u = 0.5;      % Alice 发信号态时选 Z 基的概率
p.Pza_v = 0.5;      % Alice 发诱骗态时选 Z 基的概率
p.Pzb   = 0.5;      % Bob 选 Z 基的概率（Bob 不知道收到的是哪种强度）

% ---- 系统参数 ----
p.f     = 1.16;     % 纠错效率：1.0 是理论最优，1.16 表示实际纠错多花了 16% 的比特
                    % （这笔开销在 keyRateAt.m 里从密钥率中扣掉）
p.alpha = 0.2;      % 光纤损耗 (dB/km)：常见的单模光纤在 1550 nm 大约就是这个数
p.etad  = 0.5;      % Bob 的探测器效率：光子真到了，也只有一半能被抓住
p.d     = 1e-6;     % 暗计数：明明没光子，探测器自己「咔」一下的概率（每脉冲百万分之一）
p.etaA  = 0.75;     % 单光子源方案用的本地探测效率（本项目用弱相干光源，用不上，留着占位）
p.dA    = 1e-6;     % 单光子源方案的本地暗计数（同上，用不上）
p.ed    = 0.015;    % 本底误码：器件、对准不完美带来的固有错误率（1.5%）
p.e0    = 0.5;      % 真空态误码：压根没收到光子、只能瞎猜，猜错的概率自然是一半

% ---- 派生量（由上面推出来的）----
% Y0 叫「真空态响应率」：脉冲里一个光子都没有，Bob 却报告「收到了」的概率。
% Bob 有两个探测器（一个代表 0，一个代表 1），随便哪个自己瞎响都算数：
%     两个都不响的概率 = (1-d)²
%     至少响一个       = 1-(1-d)² = 2d-d² = 2d(1-d)   ← 就是下面这行
% （对应指导书 (3.27) 里真空态 Y_0 的取值）
p.Y0    = 2 * p.d * (1 - p.d);

% 真空态概率：三种脉冲加起来要是 1，所以 P0 = 1 - Pu - Pv = 1-0.6-0.3 = 0.1。
% 注意：优化器改 Pu、Pv 的时候，P0 会跟着变（runCase.m 里会自动重算）。
p.P0    = 1 - p.Pu - p.Pv;

end
